export function Information({ path }: { path: string }) {
  const page = SITE_PAGES.find((page) => page.path === path);
  const missing = !page;
  return (
    <>
      <a className="skip-link" href="#information">
        본문으로 건너뛰기
      </a>
      <SiteHeader />
      <main id="information" className="shell information" tabIndex={-1}>
        {path === '/about/' && <About />}
        {path === '/privacy/' && <Privacy />}
        {path === '/terms/' && <Terms />}
        {missing && (
          <>
            <h1>페이지를 찾을 수 없어요</h1>
            <p>
              <a href="/">메뉴 검색으로 돌아가기</a>
            </p>
          </>
        )}
      </main>
      <SiteFooter />
    </>
  );
}
